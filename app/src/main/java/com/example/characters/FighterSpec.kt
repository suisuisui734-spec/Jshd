enum class ElementType {
  LIGHTNING,
  FIRE,
}

enum class AttackMoveType {
  LIGHT_1,
  LIGHT_2,
  LIGHT_3,
  HEAVY_1,
  HEAVY_2,
  LAUNCHER,
  AIR_COMBO,
  SPECIAL,
  ULTIMATE,
}

data class MoveSpec(
  val type: AttackMoveType,
  val name: String,
  val animState: AnimationState,
  val startupSec: Float,
  val activeSec: Float,
  val recoverySec: Float,
  val cancelWindowStartSec: Float,
  val damage: Int,
  val chipDamage: Int,
  val guardDamage: Float,
  val hitstunSec: Float,
  val blockstunSec: Float,
  val rangeMeters: Float,
  val hitRadius: Float,
  val knockbackHorizontal: Float,
  val knockbackVertical: Float,
  val forwardLungeSpeed: Float,
  val energyGainOnHit: Float,
  val energyCost: Float,
  val cooldownSec: Float,
  val isProjectileOrArea: Boolean = false,
  val canCancelInto: Set<AttackMoveType> = emptySet(),
) {
  val totalDurationSec: Float get() = startupSec + activeSec + recoverySec
}

